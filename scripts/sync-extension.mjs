#!/usr/bin/env node
/**
 * Keep the extension's injected payloads in byte-exact sync with `lib/`.
 *
 * The extension loads its pages scripts from files, while the CDP backend
 * evaluates the same text directly, so a hand-copied file would silently drift
 * and the two backends would start behaving differently. This script is the only
 * writer of those two files, and `test/page-script.test.mjs` fails when they
 * disagree.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import { PAGE_RUNTIME_SOURCE } from '../lib/page-script.js'
import { TAP_SOURCE } from '../lib/tap-script.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')

/** Write one generated extension payload, announcing the source of truth. */
function writeGenerated(relativePath, source) {
  const banner = `/* GENERATED by scripts/sync-extension.mjs from ${relativePath.source} — edit that file, not this one. */\n`
  const target = join(root, 'extension', relativePath.target)
  writeFileSync(target, `${banner}${source}\n`, 'utf8')
  console.log(`wrote ${relativePath.target} (${source.length} chars)`)
}

writeGenerated({ source: 'lib/page-script.js', target: 'injected-page.js' }, PAGE_RUNTIME_SOURCE)
writeGenerated({ source: 'lib/tap-script.js', target: 'injected-tap.js' }, TAP_SOURCE)

// Fail loudly if the two copies already disagree, so a stale checkout cannot pass.
for (const { target, source, module } of [
  { target: 'injected-page.js', source: PAGE_RUNTIME_SOURCE, module: 'lib/page-script.js' },
  { target: 'injected-tap.js', source: TAP_SOURCE, module: 'lib/tap-script.js' },
]) {
  const text = readFileSync(join(root, 'extension', target), 'utf8')
  if (!text.includes(source)) {
    console.error(`error: ${target} does not contain ${module}; the sync failed`)
    process.exitCode = 1
  }
}
